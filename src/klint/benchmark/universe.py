def get_all_tickers() -> List[Dict[str, str]]:
    """Returns a flat list of all asset items with asset_class annotated."""
    all_assets = []
    for asset_class, assets in BENCHMARK_UNIVERSE.items():
        for item in assets:
            all_assets.append({
                "ticker": item["ticker"],
                "name": item["name"],
                "asset_class": asset_class,
            })
    return all_assets


def get_universe_by_class(asset_class: str) -> List[Dict[str, str]]:
    """Returns assets for a specific asset class."""
    return BENCHMARK_UNIVERSE.get(asset_class, [])
